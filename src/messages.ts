type Locale = keyof typeof CATALOGS;
type MessageKey = keyof (typeof CATALOGS)['en-US'];

function normalizeLocale(value: unknown): Locale | null {
  if (!value) return null;
  const normalized = String(value).replace('_', '-').toLowerCase();
  if (normalized === 'en' || normalized === 'en-us') return 'en-US';
  if (normalized === 'br' || normalized === 'pt' || normalized === 'pt-br') return 'pt-BR';
  return null;
}

type ResolveLocaleInput = {
  explicit?: unknown;
  configured?: unknown;
};

function resolveLocale({ explicit, configured }: ResolveLocaleInput = {}): Locale {
  return normalizeLocale(explicit) || normalizeLocale(configured) || 'en-US';
}

type MessageValues = Record<string, string | number | undefined>;

function t(locale: string, key: MessageKey | string, values: MessageValues = {}): string {
  const normalized = normalizeLocale(locale) || 'en-US';
  const catalog = CATALOGS[normalized] as Record<string, string>;
  const fallback = CATALOGS['en-US'] as Record<string, string>;
  const template = catalog[key] || fallback[key] || key;
  return template.replace(/\{(\w+)\}/g, (_: string, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

function translateText(locale: string, text: unknown): string {
  if (normalizeLocale(locale) !== 'pt-BR') return String(text);
  const replacements: [RegExp, string][] = [
    [/^preserved existing /, 'configuração existente preservada '],
    [/^wrote /, 'gravado '],
    [/^created /, 'criado '],
    [/^initialized /, 'inicializado '],
    [/^preserved /, 'preservado '],
    [/^saved /, 'salvo '],
    [/^installed /, 'instalado '],
    [/^removed /, 'removido '],
    [/^refreshed /, 'atualizado '],
    [/^PASS policy updated$/, 'PASS política atualizada'],
    [/^Already up to date\.$/, 'Já está atualizado.'],
    [
      /^nothing installed by sdd-agentic-flow was found$/,
      'nenhuma instalação do sdd-agentic-flow foi encontrada',
    ],
    [/^No changes were made\.$/, 'Nenhuma alteração foi feita.'],
    [/^unable to check for updates$/, 'não foi possível verificar atualizações'],
    [/^installation completed but /, 'a instalação foi concluída, mas '],
    [/^installation is current but /, 'a instalação está atualizada, mas '],
    [
      /^Managed skills differ from package and will be updated after confirmation\.$/,
      'As skills gerenciadas diferem do pacote e serão atualizadas após confirmação.',
    ],
    [
      /^skipped differing files \(no silent overwrite\)$/,
      'arquivos diferentes ignorados (sem sobrescrita silenciosa)',
    ],
    [
      /^no skill files refreshed \(all candidates differed or were identical\)$/,
      'nenhum arquivo de skill foi atualizado (todos eram diferentes ou idênticos)',
    ],
  ];
  return replacements.reduce(
    (value, [pattern, replacement]) => value.replace(pattern, replacement),
    String(text),
  );
}

function validateCatalogParity(): boolean {
  const expected = Object.keys(CATALOGS['en-US']).sort().join('\n');
  return Object.values(CATALOGS).every(
    (catalog) => Object.keys(catalog).sort().join('\n') === expected,
  );
}

